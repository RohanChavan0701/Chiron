"""Run 5 four-arm summary: per-arm accuracy, test-suite-corrected accuracy and paired differences.

Reads runs_v5/summary.csv and runs_v5/s<SEED>/audit.json, writes runs_v5/arm_stats.md and
prints it. Stdlib only. Run from rsi_pilot: python scripts/arm_stats.py
"""
import csv
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from rsi.pool import wilcoxon_exact  # noqa: E402

RUNS = ROOT / "runs_v5"
HARNESSES = ["baseline", "arm_A", "arm_B", "arm_C"]
LABELS = {
    "baseline": "baseline (unevolved harness)",
    "arm_A": "A (32B proposer, keep any gain)",
    "arm_B": "B (regularized, RRSI-style)",
    "arm_C": "C (random edits, A's keep rule)",
}
COMPARISONS = [
    ("arm_A", "arm_C", "pre-registered: LLM proposer vs random edits"),
    ("arm_B", "arm_C", ""),
    ("arm_B", "arm_A", ""),
    ("arm_A", "baseline", ""),
    ("arm_B", "baseline", ""),
    ("arm_C", "baseline", ""),
]


def load(runs: Path = RUNS) -> dict:
    """Per seed and harness: raw passes and test-suite-corrected passes on H, passes on B,
    n_H, n_B and tokens per H task."""
    rows = list(csv.DictReader(open(runs / "summary.csv", encoding="utf-8")))
    seeds = sorted({r["seed"] for r in rows})
    data = {}
    for s in seeds:
        audit = json.loads((runs / f"s{s}" / "audit.json").read_text(encoding="utf-8"))
        for r in rows:
            if r["seed"] != s:
                continue
            h = r["harness"]
            a = audit[f"{h}/H"]
            if a["passes"] != int(r["H"]):
                raise ValueError(f"seed {s} {h}: audit passes {a['passes']} != summary H {r['H']}")
            if a["testsuite_checked"] != a["passes"]:
                raise ValueError(f"seed {s} {h}: not every H pass was test-suite checked")
            data[(s, h)] = {
                "H": int(r["H"]),
                "H_fp": a["testsuite_false_positives"],
                "H_ts": int(r["H"]) - a["testsuite_false_positives"],
                "H_gold_empty": a["gold_empty_passes"],
                "B": int(r["B"]),
                "n_H": int(r["n_H"]),
                "n_B": int(r["n_B"]),
                "tokens": int(r["tokens_per_task_H"]),
            }
    return {"seeds": seeds, "data": data}


def pct(d: dict, s: str, h: str, key: str) -> float:
    n = d["data"][(s, h)]["n_B" if key == "B" else "n_H"]
    return 100 * d["data"][(s, h)][key] / n


def mean_sd(xs: list[float]) -> tuple[float, float]:
    return statistics.mean(xs), statistics.stdev(xs)


def compute(runs: Path = RUNS) -> dict:
    d = load(runs)
    seeds = d["seeds"]
    out = {"seeds": seeds, "per_seed": {}, "arms": {}, "diffs": {}}
    for h in HARNESSES:
        out["per_seed"][h] = {k: [pct(d, s, h, k) for s in seeds] for k in ("H", "H_ts", "B")}
        rec = {k: mean_sd(v) for k, v in out["per_seed"][h].items()}
        passes = sum(d["data"][(s, h)]["H"] for s in seeds)
        fps = sum(d["data"][(s, h)]["H_fp"] for s in seeds)
        rec["fp_share"] = 100 * fps / passes
        rec["gold_empty"] = sum(d["data"][(s, h)]["H_gold_empty"] for s in seeds)
        rec["tokens"] = statistics.mean(d["data"][(s, h)]["tokens"] for s in seeds)
        out["arms"][h] = rec
    for x, y, note in COMPARISONS:
        rec = {"note": note}
        for k in ("H", "H_ts", "B"):
            diffs = [a - b for a, b in zip(out["per_seed"][x][k], out["per_seed"][y][k])]
            m, sd = mean_sd(diffs)
            rec[k] = {"per_seed": diffs, "mean": m, "sd": sd,
                      "positive": sum(v > 0 for v in diffs), "negative": sum(v < 0 for v in diffs),
                      "p": wilcoxon_exact(diffs)}
        out["diffs"][(x, y)] = rec
    return out


def short(h: str) -> str:
    return "baseline" if h == "baseline" else h.split("_")[1]


def render(r: dict) -> str:
    seeds = r["seeds"]
    L = []
    L.append("Generated by scripts/arm_stats.py from runs_v5/summary.csv and "
             "runs_v5/s<SEED>/audit.json (key <harness>/H).")
    L.append("")
    L.append("# Run 5: four arms on held-out Spider (H) and BIRD (B)")
    L.append("")
    L.append(f"{len(seeds)} seeds ({', '.join(seeds)}). H = the same 200 Spider-dev tasks in every "
             "seed; B = the same 200 BIRD Mini-Dev tasks. SD is the sample SD over seeds (ddof 1). "
             "Test-suite-corrected = (passes - test-suite false positives) / 200, where a false "
             "positive passes on the single evaluation database but fails on Spider's distilled "
             "test-suite databases. The baseline is one harness re-scored once per seed, so its "
             "spread is rerun noise.")
    L.append("")
    L.append("## (a) Held-out Spider accuracy per seed (%)")
    L.append("")
    L.append("| Seed | " + " | ".join(short(h) for h in HARNESSES) + " |")
    L.append("|---|" + "---:|" * len(HARNESSES))
    for i, s in enumerate(seeds):
        L.append(f"| {s} | " + " | ".join(f"{r['per_seed'][h]['H'][i]:.1f}" for h in HARNESSES) + " |")
    L.append("")
    L.append("## (b) Per arm, held-out Spider: mean (SD) over seeds")
    L.append("")
    L.append("| Harness | Raw % | Test-suite-corrected % | False-positive share of passes "
             "(pooled) | Gold-empty passes | Tokens per H task |")
    L.append("|---|---:|---:|---:|---:|---:|")
    for h in HARNESSES:
        a = r["arms"][h]
        L.append(f"| {LABELS[h]} | {a['H'][0]:.2f} ({a['H'][1]:.2f}) | "
                 f"{a['H_ts'][0]:.2f} ({a['H_ts'][1]:.2f}) | {a['fp_share']:.1f}% | "
                 f"{a['gold_empty']} | {a['tokens']:.0f} |")
    L.append("")
    L.append("## (c) Paired per-seed differences on held-out Spider (percentage points)")
    L.append("")
    L.append("Exact two-sided Wilcoxon signed-rank p over seeds (rsi.pool.wilcoxon_exact; zeros "
             "dropped). With 6 seeds the smallest attainable p is 0.031. Only A minus C is a "
             "pre-registered endpoint here; the others are descriptive.")
    L.append("")
    L.append("| Difference | Scoring | Per-seed values | Mean | SD | +/- seeds | p |")
    L.append("|---|---|---|---:|---:|---|---:|")
    for (x, y), rec in r["diffs"].items():
        name = f"{short(x)} minus {short(y)}"
        if rec["note"]:
            name += f" ({rec['note']})"
        for k, lab in (("H", "raw"), ("H_ts", "test-suite")):
            v = rec[k]
            vals = ", ".join(f"{t:+.1f}" for t in v["per_seed"])
            L.append(f"| {name} | {lab} | {vals} | {v['mean']:+.2f} | {v['sd']:.2f} | "
                     f"{v['positive']}/{v['negative']} | {v['p']:.3f} |")
    L.append("")
    L.append("## (d) Per arm, BIRD Mini-Dev: mean (SD) over seeds, raw only (no test suite)")
    L.append("")
    L.append("| Harness | BIRD % |")
    L.append("|---|---:|")
    for h in HARNESSES:
        a = r["arms"][h]
        L.append(f"| {LABELS[h]} | {a['B'][0]:.2f} ({a['B'][1]:.2f}) |")
    L.append("")
    L.append("| Difference | Per-seed values (pp) | Mean | SD | +/- seeds | p |")
    L.append("|---|---|---:|---:|---|---:|")
    for (x, y), rec in r["diffs"].items():
        v = rec["B"]
        vals = ", ".join(f"{t:+.1f}" for t in v["per_seed"])
        L.append(f"| {short(x)} minus {short(y)} | {vals} | {v['mean']:+.2f} | {v['sd']:.2f} | "
                 f"{v['positive']}/{v['negative']} | {v['p']:.3f} |")
    L.append("")
    return "\n".join(L)


def main() -> None:
    text = render(compute())
    (RUNS / "arm_stats.md").write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
